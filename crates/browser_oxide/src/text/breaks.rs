/// Whether Chrome allows a line break between `a` and `b`, if both are printable
/// ASCII other than a space; `None` for anything else.
pub fn ascii_break_allowed(a: char, b: char) -> Option<bool> {
    let index = |c: char| (c.is_ascii_graphic()).then(|| c as usize - 33);
    Some((ALLOWED[index(a)?] >> index(b)?) & 1 == 1)
}
